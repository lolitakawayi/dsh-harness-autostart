/**
 * dsh-autostart —— 让 DeepSeek Harness 随 Windows 开机自启，并以工具形式管理该启动项。
 *
 * 支持两种落地方式：
 *   run-key         HKCU\Software\Microsoft\Windows\CurrentVersion\Run（不需要管理员）
 *   startup-folder  %APPDATA%\Microsoft\Windows\Start Menu\Programs\Startup 下的 .cmd 启动器
 *
 * 宿主半侧只做三件事：读配置 → 确保/撤销启动项 → 注册 dsh_autostart 工具。
 */
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const run = promisify(execFile);

export const name = 'dsh-autostart';
export const inject = ['tools', 'webServer'];

const RUN_KEY = 'HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Run';

/** 设置页开关使用的本机 HTTP 入口，避开其它插件的路由前缀。 */
const ROUTE_PREFIX = '/dsh-autostart-8f3c';

export function apply(ctx, config = {}) {
  const state = resolveConfig(config);

  // ---- 启动项读写 ---------------------------------------------------------
  function startupCmdPath() {
    const appData = process.env.APPDATA || path.join(os.homedir(), 'AppData', 'Roaming');
    return path.join(appData, 'Microsoft', 'Windows', 'Start Menu', 'Programs', 'Startup', `${state.entryName}.cmd`);
  }

  function launchTarget() {
    const args = state.args.length ? ' ' + state.args.map(quote).join(' ') : '';
    return `${quote(state.executable)}${args}`;
  }

  async function readRunKey() {
    try {
      const { stdout } = await run('reg', ['query', RUN_KEY, '/v', state.entryName]);
      const m = /REG_SZ\s+(.+?)\s*$/m.exec(stdout);
      return m ? m[1] : null;
    } catch {
      return null;
    }
  }

  async function writeRunKey() {
    const value = state.delaySeconds > 0
      ? `${quote(cmdExe())} /c start "" ${quote(launchTarget())}`
      : launchTarget();
    await run('reg', ['add', RUN_KEY, '/v', state.entryName, '/t', 'REG_SZ', '/d', value, '/f']);
    return value;
  }

  async function deleteRunKey() {
    try {
      await run('reg', ['delete', RUN_KEY, '/v', state.entryName, '/f']);
      return true;
    } catch {
      return false;
    }
  }

  function writeStartupFile() {
    const target = startupCmdPath();
    fs.mkdirSync(path.dirname(target), { recursive: true });
    const delay = state.delaySeconds > 0
      ? `timeout /t ${state.delaySeconds} /nobreak >nul\r\n`
      : '';
    const body = [
      '@echo off',
      'rem Generated by dsh-autostart. Delete this file to stop DeepSeek Harness autostart.',
      delay + `start "" ${launchTarget()}`,
      '',
    ].join('\r\n');
    fs.writeFileSync(target, body, 'latin1');
    return target;
  }

  function removeStartupFile() {
    const target = startupCmdPath();
    if (!fs.existsSync(target)) return false;
    fs.rmSync(target, { force: true });
    return true;
  }

  async function status() {
    const file = startupCmdPath();
    const runValue = state.method === 'run-key' ? await readRunKey() : null;
    const usable = state.method === 'startup-folder' ? fs.existsSync(file) : Boolean(runValue);
    return {
      ok: true,
      enabled: usable,
      method: state.method,
      entryName: state.entryName,
      executable: state.executable || '',
      args: state.args.join(' '),
      delaySeconds: state.delaySeconds,
      runKeyValue: runValue || '',
      startupFile: state.method === 'startup-folder' ? file : '',
      platform: process.platform,
      reason: usable ? '' : '启动项当前不存在',
    };
  }

  async function enable() {
    if (process.platform !== 'win32') {
      return { ok: false, enabled: false, reason: 'unsupported-platform', platform: process.platform };
    }
    if (state.method === 'startup-folder') {
      writeStartupFile();
      return await status();
    }
    await writeRunKey();
    return await status();
  }

  async function disable() {
    if (process.platform !== 'win32') {
      return { ok: false, enabled: false, reason: 'unsupported-platform', platform: process.platform };
    }
    const removed = state.method === 'startup-folder' ? removeStartupFile() : await deleteRunKey();
    const view = await status();
    return { ...view, removed };
  }

  const log = (message) => {
    try { ctx.logger?.warn?.(`dsh-autostart: ${message}`); } catch { /* logging is best effort */ }
  };

  // ---- 安装即生效 ---------------------------------------------------------
  if (state.autoEnable) {
    ctx.effect(() => {
      enable().then(
        (r) => { if (!r.ok) log(`启动项写入失败 ${JSON.stringify(r)}`); },
        (e) => log(e && e.message ? e.message : String(e)),
      );
      // 卸载插件时撤销启动项，避免留下孤儿条目
      return () => { disable().catch(() => {}); };
    });
  }

  // ---- 让运行中的 Harness 重新扫描本包的客户端声明 -----------------------
  // clientModules 会按 (baseUrl, 包名) 缓存每个包的 package.json 元数据，
  // 首次扫描时本包还没有 dsh.client 时缓存值就是 null，之后新加的客户端半边
  // 不会再被读取。这里主动丢掉那一格缓存并重排一次，浏览器无需重启即可拿到
  // client.js；缓存本来就是正确的环境里这一段是空操作。
  ctx.effect(() => {
    const clientModules = ctx.get?.('clientModules');
    if (!clientModules || typeof clientModules.flush !== 'function') return () => {};
    // 未被注册进 client graph 才需要重扫
    if (clientModules.graph?.().entries?.some((entry) => entry.id === 'dsh-harness-autostart')) return () => {};
    try {
      for (const key of [...(clientModules.pkgMeta?.keys?.() ?? [])]) {
        if (typeof key === 'string' && key.includes('dsh-harness-autostart')) clientModules.pkgMeta.delete(key);
      }
      if (clientModules.dirty?.add) clientModules.dirty.add('dsh-harness-autostart');
      clientModules.flush((error) => log(error && error.message ? error.message : String(error)));
    } catch (error) {
      log(`重新扫描客户端半边失败：${error && error.message ? error.message : String(error)}`);
    }
    return () => {};
  }, 'dsh-autostart: client graph rescan');

  // ---- 设置页开关使用的本机 HTTP 接口 -------------------------------------
  // 客户端半边（client.js）不允许直接碰 Node 能力，通过同源 fetch 调这里。
  ctx.effect(() => ctx.webServer.register({
    kind: 'prefix',
    path: ROUTE_PREFIX,
    handler: async (req, res) => {
      const url = typeof req.url === 'string' ? req.url : ROUTE_PREFIX;
      const action = url.slice(ROUTE_PREFIX.length).replace(/^\/+/, '').split('?')[0] || 'status';
      try {
        if (action === 'enable') {
          const view = await enable();
          sendJson(res, view.ok ? 200 : 500, view);
          return;
        }
        if (action === 'disable') {
          const view = await disable();
          sendJson(res, view.ok === false && view.reason === 'unsupported-platform' ? 500 : 200, view);
          return;
        }
        if (action === 'status') {
          sendJson(res, 200, await status());
          return;
        }
        sendJson(res, 404, { ok: false, error: 'unknown-action', action });
      } catch (error) {
        sendJson(res, 500, { ok: false, error: error && error.message ? error.message : String(error) });
      }
    },
  }), 'dsh-autostart: settings switch route');

  // ---- 模型可调用的工具 ---------------------------------------------------
  /** dsh_autostart —— 查看 / 开启 / 关闭开机自启项。 */
  const tool = {
    name: 'dsh_autostart',
    description:
      '查看、开启或关闭 DeepSeek Harness 的 Windows 开机自启项。action=status 返回当前配置与是否已启用；action=enable 写入启动项；action=disable 删除启动项。',
    parameters: {
      type: 'object',
      properties: {
        action: {
          type: 'string',
          enum: ['status', 'enable', 'disable'],
          description: '要执行的动作。',
        },
      },
      required: ['action'],
      additionalProperties: false,
    },
    output: {
      schema: {
        type: 'object',
        properties: {
          ok: { type: 'boolean' },
          enabled: { type: 'boolean' },
          method: { type: 'string' },
          entryName: { type: 'string' },
          executable: { type: 'string' },
          runKeyValue: { type: 'string' },
          startupFile: { type: 'string' },
          reason: { type: 'string' },
        },
        additionalProperties: true,
      },
      render: (_args, value) => [{ type: 'text', text: renderStatus(value) }],
    },
    async execute(args) {
      const action = (args && args.action) || 'status';
      if (action === 'enable') return await enable();
      if (action === 'disable') return await disable();
      return await status();
    },
  };

  return ctx.effect(() => ctx.tools.register(tool));
}

function renderStatus(v) {
  if (!v || typeof v !== 'object') return String(v);
  const lines = [];
  lines.push(v.enabled ? 'DeepSeek Harness 开机自启：已启用' : 'DeepSeek Harness 开机自启：未启用');
  if (v.method) lines.push(`方式：${v.method === 'startup-folder' ? '启动文件夹' : '注册表 Run 键'}`);
  if (v.entryName) lines.push(`条目名：${v.entryName}`);
  if (v.executable) lines.push(`可执行文件：${v.executable}`);
  if (v.runKeyValue) lines.push(`Run 值：${v.runKeyValue}`);
  if (v.startupFile) lines.push(`启动文件：${v.startupFile}`);
  if (v.reason) lines.push(`说明：${v.reason}`);
  return lines.join('\n');
}

// ---- 辅助 ---------------------------------------------------------------
function quote(s) {
  const str = String(s);
  return /[\s"]/.test(str) ? `"${str.replace(/"/g, '""')}"` : str;
}

/** 往 Node 原始 response 写一段 JSON（设置页开关的唯一传输格式）。 */
function sendJson(res, status, value, headers = {}) {
  const body = JSON.stringify(value);
  res.writeHead(status, {
    'content-type': 'application/json; charset=utf-8',
    'content-length': Buffer.byteLength(body),
    'cache-control': 'no-store',
    ...headers,
  });
  res.end(body);
}

function cmdExe() {
  return process.env.ComSpec || 'C:\\Windows\\System32\\cmd.exe';
}

function resolveConfig(config) {
  const exe = typeof config.executable === 'string' && config.executable.trim()
    ? config.executable.trim()
    : detectExecutable();
  const args = Array.isArray(config.args) ? config.args.map(String) : [];
  const method = config.method === 'startup-folder' ? 'startup-folder' : 'run-key';
  const rawName = typeof config.entryName === 'string' && config.entryName.trim()
    ? config.entryName.trim()
    : 'DeepSeekHarness';
  const entryName = rawName.replace(/[^A-Za-z0-9_.-]/g, '') || 'DeepSeekHarness';
  const delaySeconds = Number.isFinite(config.delaySeconds) ? Math.max(0, Math.floor(config.delaySeconds)) : 0;
  return {
    autoEnable: config.autoEnable !== false,
    method,
    entryName,
    executable: exe,
    args,
    delaySeconds,
  };
}

/** 优先取桌面端 Harness 可执行文件；在纯 CLI 环境下退回当前进程。 */
function detectExecutable() {
  if (process.env.DSH_DESKTOP_EXE) return process.env.DSH_DESKTOP_EXE;
  const exe = process.execPath;
  // Electron 外壳进程：execPath 就是 "DeepSeek Harness.exe"
  if (/\.exe$/i.test(exe) && !/(^|[\\/])node\.exe$/i.test(exe)) return exe;
  const known = 'D:\\ProgramData\\dsh\\DeepSeek Harness.exe';
  if (fs.existsSync(known)) return known;
  return exe;
}
